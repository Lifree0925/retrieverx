"""
scripts/make_enterprise_corpus.py —— 生成 RetrieverX 的企业级文档语料

【为什么需要它】
  仓库里只有一份《PX-4200 产品手册》，它能验证"链路通不通"，
  但验证不了这些**只有在多文档、多主题语料上才暴露**的问题：
    · 跨文档抢位：问 A 文档的问题，被 B 文档里字面更像的段落挤掉；
    · 文档范围限定：`document_id` 过滤到底有没有生效（单文档时永远"生效"）；
    · 标题层级判定：不同文档的标题字号习惯不同（手册用 15~20pt，制度类常用 14~16pt）；
    · 表格与正文混杂：制度类文档里"时限/额度"几乎全在表格里，靠正文检索会漏。
  所以这里生成 6 份风格各异的文档，构成一个像样的"企业知识库"。

【⚠️ 两条容易踩的约束，改这个文件前先读】

  1. **PDF 内容变了，chunk_id 就全变。**
     `document_id` 由文件内容 sha256 派生，`chunk_id` 再由 document_id 派生。
     所以顺序必须是「先定稿语料 → 再建索引 → 最后造评测集」。
     造完评测集又回头改 PDF，评测集里的 chunk_id 会集体失效，
     表现是"Recall 突然掉到 0"——极难联想到是 PDF 本身变了。

  2. **每一节的正文要写到 300 字符以上，否则不会独立成 chunk。**
     `StructureAwareChunker` 的换节门槛是 `section_min_chars`（默认 min_chars//4 = 300）：
     上一节没攒够 300 字符就换节，内容会和下一节合并成一个 chunk。
     结果是"一个 chunk 覆盖半份文档"，检索任务退化成"猜是哪份文档"，
     评测也就测不出细粒度的检索质量。
     本文件里每节都按 350~600 字符写，实测 6 份文档产出 40+ 个 chunk。

【用法】
  cd retrieverx
  venv\\Scripts\\python.exe scripts/make_enterprise_corpus.py
  venv\\Scripts\\python.exe scripts/make_enterprise_corpus.py --only 员工手册 IT服务
"""
