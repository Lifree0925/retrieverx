DOCUMENTS = {
    "QX8800": doc_qx8800,
    "员工手册": doc_hr,
    "IT服务": doc_itsop,
    "信息安全": doc_security,
    "采购制度": doc_procurement,
    "财务报销": doc_finance,
}


def main() -> None:
    parser = argparse.ArgumentParser(description="生成 RetrieverX 企业级文档语料")
    parser.add_argument("--only", nargs="*", default=None,
                        help=f"只生成指定文档，可选：{'/'.join(DOCUMENTS)}")
    parser.add_argument("--out-dir", default=str(CORPUS_DIR))
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    keys = args.only or list(DOCUMENTS)
    unknown = [k for k in keys if k not in DOCUMENTS]
    if unknown:
        raise SystemExit(f"未知的文档键: {unknown}；可选 {list(DOCUMENTS)}")

    from app.core.chunker import StructureAwareChunker
    from app.core.parser import PDFParser

    pdf_parser = PDFParser()
    chunker = StructureAwareChunker()
    index: dict[str, dict] = {}
    if INDEX_PATH.exists():
        try:
            index = json.loads(INDEX_PATH.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            index = {}

    print(f"生成目录: {out_dir}\n")
    for key in keys:
        title, blocks = DOCUMENTS[key]()
        path = out_dir / f"{title}.pdf"
        render_document(path, blocks)
        raw = path.read_bytes()
        parsed = pdf_parser.parse_pdf(path)
        chunks = chunker.chunk(parsed)
        index[path.name] = {
            "key": key,
            "title": title,
            "sha256": hashlib.sha256(raw).hexdigest(),
            "size_bytes": len(raw),
            "blocks": len(parsed),
            "chunks": len(chunks),
            "pages": max((b.page_number for b in parsed), default=0),
            "table_blocks": sum(1 for b in parsed if b.content_type == "table"),
            "headings": sorted({"/".join(b.heading_path)
                                for b in parsed if b.heading_path}),
        }
        info = index[path.name]
        print(f"  [OK] {path.name}")
        print(f"       {len(raw) / 1024:.1f} KB | {info['pages']} 页 | "
              f"{info['blocks']} 块（含 {info['table_blocks']} 个表格）| {info['chunks']} chunks")

    INDEX_PATH.parent.mkdir(parents=True, exist_ok=True)
    INDEX_PATH.write_text(json.dumps(index, ensure_ascii=False, indent=2), encoding="utf-8")

    total_chunks = sum(v["chunks"] for v in index.values())
    print(f"\n语料索引: {INDEX_PATH}")
    print(f"共 {len(index)} 份文档 / {total_chunks} 个 chunk")
    if total_chunks < 30:
        print(f"\n[警告] chunk 总数只有 {total_chunks}，偏少。"
              "检查是不是某几节的正文不足 300 字符（那样不会独立成 chunk）。")
    print("\n下一步（顺序不能反）：")
    print("  1) python scripts/index_documents.py data/corpus/*.pdf   # 建索引")
    print("  2) python scripts/build_eval_set.py                      # 造评测集")
    print("  改完 PDF 必须重跑这两步——chunk_id 由文件内容哈希派生，改了就对不上。")


if __name__ == "__main__":
    main()
